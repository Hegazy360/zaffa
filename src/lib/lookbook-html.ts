import "server-only";
import { getTranslations } from "next-intl/server";
import { fontFaceCss } from "@/lib/pdf";
import { isRtlLocale } from "@/i18n/config";
import { uiLocaleTag } from "@/lib/money-format";
import {
  REPLY_WITHIN_HOURS,
  WHATSAPP_LINK,
  WHATSAPP_NUMBER_DISPLAY,
} from "@/lib/contact-channels";

/**
 * The lookbook, as HTML for Chromium to print.
 *
 * Written as a string rather than a React tree on purpose: this is a print
 * document with page rules, not an app surface, and the CSS it needs
 * (`@page`, `break-inside`, `print-color-adjust`) has nothing to do with the
 * rest of the design system. Keeping it in one file means the whole artefact
 * a customer paid for can be read top to bottom.
 *
 * Page plan (ZAF-79 — the "longer, more detailed" rebuild):
 *   1. Cover — name, design, palette swatches + palette name, guest count.
 *   2. Details — the brief spelled out: event type, setting, size, guests,
 *      palette with hex captions.
 *   3. One moodboard page PER reference category, with attribution lines —
 *      the Pinterest credit is part of what makes the board usable with a
 *      real vendor.
 *   4. Style notes, when the couple wrote any.
 *   5. Up to 16 render pages, newest first.
 *   6. Microsite page — URL + QR handed in by the route as a data URL, so
 *      the print document makes no network request for it.
 *   7. "Make it real" — the concierge closing page. فصحى: this page is a
 *      commitment surface.
 *
 * Everything that made the old react-pdf version unable to serve the primary
 * market stays fixed structurally: `dir`/`lang` on the root so Chromium does
 * the shaping and bidi; fonts inlined from disk (a CDN blip must not swap
 * Arabic for tofu); every string translated and dates through
 * `Intl.DateTimeFormat` in the reader's locale.
 */

export interface LookbookData {
  recipientName: string;
  publishedAt: Date | null;
  /** Absolute microsite URL, or null when no slug was allocated. */
  micrositeUrl: string | null;
  /** QR for `micrositeUrl` as a data URL — generated by the route. */
  micrositeQrDataUrl: string | null;
  design: {
    name: string | null;
    event_type: string | null;
    setting: string | null;
    size: string | null;
    guest_count: number | null;
    palette: { name?: string; colors: string[] };
    /** Keyed by reference category. A partial record rather than a
     *  total one, because the designer can add a category before this file
     *  knows about it and a missing bucket must read as empty, not crash. */
    references: Partial<
      Record<string, { id: string; url: string; attribution?: string; sourceUrl?: string }[]>
    >;
    style_notes: string | null;
    media: { id: string; type: string; url: string }[];
  };
}

const CATEGORY_ORDER = [
  "overall_vibe",
  "venue_decor",
  "tables",
  "flowers",
  "lighting",
] as const;

/** More pages than the old 12 — the pack now includes 20 renders — but
 *  still capped: every render is an image Chromium must download before
 *  printing, and the route has a hard timeout. Newest first. */
const MAX_RENDER_PAGES = 16;

/** Escape for HTML text and attribute contexts. Everything interpolated below
 *  is customer-supplied (a design name, style notes, their own name, a
 *  Pinterest attribution), so it all goes through here — a lookbook is not a
 *  place to discover an injection. */
function esc(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export async function renderLookbookHtml(
  data: LookbookData,
  locale: string,
): Promise<string> {
  const [t, fonts] = await Promise.all([
    getTranslations("lookbook"),
    fontFaceCss(),
  ]);

  const rtl = isRtlLocale(locale);
  const { design, recipientName, publishedAt } = data;

  const dateLabel = publishedAt
    ? new Intl.DateTimeFormat(uiLocaleTag(locale), {
        month: "long",
        year: "numeric",
      }).format(new Date(publishedAt))
    : "";

  const categories = CATEGORY_ORDER.filter(
    (c) => (design.references[c]?.length ?? 0) > 0,
  );
  const renders = design.media
    .filter((m) => m.type === "render")
    .slice(0, MAX_RENDER_PAGES);

  // `event_type`, `setting` and `size` are enum-ish strings from the designer.
  // They resolve to translated labels, falling back to the raw value if a new
  // one appears before its copy.
  const label = (key: string, value: string | null) =>
    value ? (t.has(`${key}.${value}`) ? t(`${key}.${value}`) : value) : "";

  const guestLine =
    design.guest_count && design.guest_count > 0
      ? t("guestCountLine", {
          count: new Intl.NumberFormat(uiLocaleTag(locale)).format(
            design.guest_count,
          ),
        })
      : "";

  const meta = [
    label("eventType", design.event_type),
    label("setting", design.setting),
    label("size", design.size),
    guestLine,
  ]
    .filter(Boolean)
    .join(" · ");

  const swatches = design.palette.colors
    .slice(0, 6)
    .map((c) => `<span class="swatch" style="background:${esc(c)}"></span>`)
    .join("");

  const footer = `<footer class="page-foot"><span>${esc(t("title"))}</span><span>${esc(
    recipientName,
  )}</span></footer>`;

  const pageHead = (labelText: string) => `
        <header class="page-head">
          <span class="brand">Zaffa</span>
          <span class="label">${esc(labelText)}</span>
        </header>`;

  // ---- 2. Details page ----------------------------------------------------
  const detailRows = (
    [
      [t("labelEventType"), label("eventType", design.event_type)],
      [t("labelSetting"), label("setting", design.setting)],
      [t("labelSize"), label("size", design.size)],
      [t("labelGuests"), guestLine ? guestLine : ""],
      [t("labelPalette"), design.palette.name ?? ""],
    ] as const
  )
    .filter(([, v]) => Boolean(v))
    .map(
      ([k, v]) => `
        <div class="detail-row">
          <span class="detail-label">${esc(k)}</span>
          <span class="detail-value">${esc(v)}</span>
        </div>`,
    )
    .join("");

  const swatchCaptions = design.palette.colors
    .slice(0, 6)
    .map(
      (c) => `
        <div class="swatch-cell">
          <span class="swatch swatch-lg" style="background:${esc(c)}"></span>
          <span class="swatch-hex">${esc(c)}</span>
        </div>`,
    )
    .join("");

  const detailsPage = `
<article class="page">
  ${pageHead(t("detailsEyebrow"))}
  <h2 class="section">${esc(t("detailsTitle"))}</h2>
  <div class="details">${detailRows}</div>
  ${
    swatchCaptions
      ? `<div class="palette-block">
           <h3 class="subhead">${esc(t("labelPalette"))}${
             design.palette.name ? ` — ${esc(design.palette.name)}` : ""
           }</h3>
           <div class="swatch-grid">${swatchCaptions}</div>
         </div>`
      : ""
  }
  ${footer}
</article>`;

  // ---- 3. One moodboard page per category ---------------------------------
  const moodboardPages = categories
    .map((cat) => {
      const items = design.references[cat] ?? [];
      const cells = items
        .map((r) => {
          const credit = r.attribution
            ? `<p class="credit">${esc(r.attribution)}</p>`
            : "";
          return `<div class="cell"><img src="${esc(r.url)}" alt="" />${credit}</div>`;
        })
        .join("");
      return `
<article class="page">
  ${pageHead(t("moodboard"))}
  <h2 class="section">${esc(t(`category.${cat}`))}</h2>
  <p class="count-line">${esc(t("pictureCount", { count: items.length }))}</p>
  <div class="grid">${cells}</div>
  ${footer}
</article>`;
    })
    .join("");

  // ---- 4. Style notes -----------------------------------------------------
  const notesPage = design.style_notes
    ? `
<article class="page">
  ${pageHead(t("notesEyebrow"))}
  <h2 class="section">${esc(t("notesTitle"))}</h2>
  <p class="notes">“${esc(design.style_notes)}”</p>
  ${footer}
</article>`
    : "";

  // ---- 5. Render pages ----------------------------------------------------
  const renderPages = renders
    .map(
      (r, i) => `
<article class="page render-page">
  ${pageHead(t("renderCounter", { index: i + 1, total: renders.length }))}
  <div class="render-frame"><img src="${esc(r.url)}" alt="" /></div>
  <p class="caption">${esc(meta)}</p>
  ${footer}
</article>`,
    )
    .join("");

  // ---- 6. Microsite page --------------------------------------------------
  const micrositePage =
    data.micrositeUrl && data.micrositeQrDataUrl
      ? `
<article class="page microsite-page">
  ${pageHead(t("micrositeEyebrow"))}
  <div class="microsite-body">
    <h2 class="section">${esc(t("micrositeTitle"))}</h2>
    <p class="microsite-hint">${esc(t("micrositeScan"))}</p>
    <img class="qr" src="${esc(data.micrositeQrDataUrl)}" alt="" />
    <p class="microsite-url"><bdi>${esc(data.micrositeUrl)}</bdi></p>
  </div>
  ${footer}
</article>`
      : "";

  // ---- 7. Make it real — the concierge close ------------------------------
  const makeItRealPage = `
<article class="page cover">
  <div>
    <p class="eyebrow">${esc(t("makeItRealEyebrow"))}</p>
    <h1>${esc(t("makeItRealTitle"))}</h1>
    <div class="hairline"></div>
    <p class="meta">${esc(t("makeItRealBody", { hours: REPLY_WITHIN_HOURS }))}</p>
    <p class="meta contact-line">
      <bdi>${esc(WHATSAPP_NUMBER_DISPLAY)}</bdi> · ${esc(WHATSAPP_LINK)}
      <br/>zaffa.ai
    </p>
  </div>
</article>`;

  return `<!doctype html>
<html lang="${esc(locale)}" dir="${rtl ? "rtl" : "ltr"}">
<head>
<meta charset="utf-8" />
<title>${esc(recipientName)} — ${esc(t("title"))}</title>
<style>
${fonts}
@page { size: A4; margin: 0; }
* { box-sizing: border-box; margin: 0; padding: 0; }
html { -webkit-print-color-adjust: exact; print-color-adjust: exact; }
body {
  font-family: ${rtl ? '"Cairo"' : '"Inter"'}, sans-serif;
  color: #1c1917;
  background: #fff;
}
.page {
  width: 210mm; height: 297mm;
  padding: 18mm 16mm;
  display: flex; flex-direction: column;
  page-break-after: always; break-after: page;
  position: relative;
  background: #fff;
}
.page:last-child { page-break-after: auto; break-after: auto; }

.cover { justify-content: center; background: #18181b; color: #fdf3f0; }
.cover .eyebrow { color: rgba(253,243,240,.6); }
.cover h1 {
  font-family: ${rtl ? '"Cairo"' : '"Fraunces"'}, serif;
  font-weight: 300;
  font-size: ${rtl ? "34pt" : "38pt"};
  line-height: 1.1;
  margin-top: 8mm;
}
.cover h2 { font-weight: 400; font-size: 13pt; color: rgba(253,243,240,.75); margin-top: 4mm; }
.hairline { height: 2px; width: 44mm; margin: 8mm 0; background: linear-gradient(90deg,#e11d48,#f59e0b); }
.meta { font-size: 10pt; color: rgba(253,243,240,.65); line-height: 1.6; white-space: pre-line; }
.contact-line { margin-top: 6mm; }
.palette { display: flex; gap: 3mm; margin-top: 10mm; }
.swatch { width: 14mm; height: 14mm; border-radius: 2mm; display: block; }

.eyebrow { font-size: 8pt; letter-spacing: ${rtl ? "0" : ".22em"}; text-transform: uppercase; }
.page-head { display: flex; justify-content: space-between; align-items: baseline; margin-bottom: 10mm; }
.brand { font-family: ${rtl ? '"Cairo"' : '"Fraunces"'}, serif; font-size: 12pt; }
.label { font-size: 8pt; letter-spacing: ${rtl ? "0" : ".18em"}; text-transform: uppercase; color: #78716c; }
h2.section { font-family: ${rtl ? '"Cairo"' : '"Fraunces"'}, serif; font-weight: 300; font-size: 22pt; margin-bottom: 8mm; }
.subhead { font-size: 11pt; font-weight: 600; margin-bottom: 4mm; }

.details { display: flex; flex-direction: column; gap: 0; margin-bottom: 10mm; }
.detail-row { display: flex; justify-content: space-between; align-items: baseline; border-bottom: 1px solid #e7e5e4; padding: 4mm 0; }
.detail-label { font-size: 9pt; letter-spacing: ${rtl ? "0" : ".12em"}; text-transform: uppercase; color: #78716c; }
.detail-value { font-size: 12pt; }
.palette-block { margin-top: 4mm; }
.swatch-grid { display: flex; gap: 5mm; flex-wrap: wrap; }
.swatch-cell { display: flex; flex-direction: column; align-items: center; gap: 2mm; }
.swatch-lg { width: 20mm; height: 20mm; border-radius: 3mm; border: 1px solid #e7e5e4; }
.swatch-hex { font-size: 8pt; color: #78716c; direction: ltr; }

.count-line { font-size: 9pt; color: #78716c; margin: -6mm 0 6mm; }
.grid { display: grid; grid-template-columns: repeat(3, 1fr); gap: 4mm; align-content: start; }
.cell { break-inside: avoid; }
.cell img { width: 100%; aspect-ratio: 1; object-fit: cover; display: block; border-radius: 2mm; background: #f5f5f4; }
.credit { font-size: 7pt; color: #a8a29e; margin-top: 1.5mm; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }

.notes { margin-top: 6mm; font-size: 13pt; line-height: 1.9; color: #44403c; font-style: italic; max-width: 150mm; }

.render-page { justify-content: flex-start; }
.render-frame { flex: 1; display: flex; align-items: center; justify-content: center; overflow: hidden; border-radius: 3mm; background: #f5f5f4; }
.render-frame img { max-width: 100%; max-height: 100%; object-fit: contain; display: block; }
.caption { margin-top: 4mm; font-size: 9pt; color: #78716c; text-align: center; }

.microsite-page { justify-content: flex-start; }
.microsite-body { flex: 1; display: flex; flex-direction: column; align-items: center; justify-content: center; text-align: center; }
.microsite-hint { font-size: 10pt; color: #78716c; margin-bottom: 8mm; max-width: 120mm; line-height: 1.6; }
.qr { width: 52mm; height: 52mm; border-radius: 3mm; border: 1px solid #e7e5e4; padding: 2mm; }
.microsite-url { margin-top: 6mm; font-size: 10pt; color: #44403c; direction: ltr; }

.page-foot {
  position: absolute; inset-inline: 16mm; bottom: 12mm;
  display: flex; justify-content: space-between;
  font-size: 8pt; color: #a8a29e;
}
</style>
</head>
<body>

<article class="page cover">
  <div>
    <p class="eyebrow">${esc(t("title"))}</p>
    <h1>${esc(recipientName)}</h1>
    <h2>${esc(design.name || t("untitled"))}</h2>
    <div class="hairline"></div>
    <p class="meta">${esc(meta || t("untitled"))}${
      design.palette.name ? "\n" + esc(design.palette.name) : ""
    }${dateLabel ? "\n" + esc(t("printed", { date: dateLabel })) : ""}</p>
    ${swatches ? `<div class="palette">${swatches}</div>` : ""}
  </div>
</article>

${detailsPage}

${moodboardPages}

${notesPage}

${renderPages}

${micrositePage}

${makeItRealPage}

</body>
</html>`;
}
