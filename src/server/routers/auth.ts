import { z } from "zod";
import { TRPCError } from "@trpc/server";
import { router, protectedProcedure, publicProcedure } from "../trpc";
import { prisma } from "@/lib/prisma";
import { enforceTrpc, ipFromRequest } from "@/lib/rate-limit";
import { addToAudience } from "@/lib/resend";
import { reportError } from "@/lib/logger";
import { verifyTurnstile } from "@/lib/turnstile";
import { getSupabaseAdmin } from "@/lib/supabase/admin";

/**
 * Auth-flow tRPC procedures that wrap the Supabase Auth client.
 *
 * Today the only public surface is `requestEmailUpgrade`, which an
 * anonymous visitor calls from the venue-designer's email gate to
 * (a) lock the email globally so it can't be reused for a second free
 * render, (b) record the capture event for analytics + Resend
 * reconciliation, and (c) push the address into Resend Audiences. The
 * actual Supabase `updateUser({ email })` call happens on the client
 * side so the magic-link email is generated by Supabase's transport
 * pipeline - this mutation is the durable, server-side side effects
 * that surround it.
 */
export const authRouter = router({
  /**
   * Anonymous visitor submitting their email at the post-render gate.
   *
   * Server-side side effects (in order):
   *   1. Rate-limit by IP, defence-in-depth against bots harvesting
   *      a list of valid-looking emails.
   *   2. Look up the lowercased email in `profiles.free_render_email`.
   *      A match means another visitor already burned a free render
   *      with that address; we refuse here with `EMAIL_ALREADY_USED_FREE`
   *      and let the UI surface the buy CTA instead.
   *   3. Stamp the email onto the caller's `Profile.free_render_email`
   *      column (UNIQUE), claiming the lock for the current anonymous
   *      user. If they never confirm, the cleanup cron eventually
   *      removes the row and frees the lock.
   *   4. Write an `EmailCaptureEvent` row (status=pending) for the
   *      reconcile cron and downstream analytics.
   *   5. Best-effort push to Resend Audiences. Failure is logged but
   *      doesn't fail the mutation, the email-confirmation magic-link
   *      flow runs regardless, and the reconcile cron picks up any
   *      `status='pending'` rows whose `resend_synced_at` is null.
   *
   * The client then calls `supabase.auth.updateUser({ email })` with
   * the active anonymous session, that triggers the confirmation
   * email to be sent via Supabase's auth transport. The link lands on
   * `/auth/confirm` which calls `verifyOtp` and redirects to
   * `/r/{renderId}`, at which point the user is fully permanent.
   */
  requestEmailUpgrade: protectedProcedure
    .input(
      z.object({
        email: z.string().email().max(254),
        designId: z.string().uuid().nullish(),
        renderId: z.string().uuid().nullish(),
        // Cloudflare Turnstile token from the gate form. Required in
        // production (`TURNSTILE_SECRET_KEY` set); skipped in dev.
        turnstileToken: z.string().max(2048).nullish(),
      }),
    )
    .mutation(async ({ ctx, input }) => {
      // We only accept this from anonymous users, a permanent account
      // already has an email and doesn't need the gate. Posting from
      // a permanent session is almost certainly a bug; surface it
      // loudly so it's obvious.
      if (!ctx.user.is_anonymous) {
        throw new TRPCError({
          code: "BAD_REQUEST",
          message: "ALREADY_PERMANENT",
        });
      }

      const ip = ctx.req ? ipFromRequest(ctx.req) : "unknown";

      // Bot protection at the email-capture surface. Same secret as
      // the renderScene gate; one widget can be reused for both.
      const tsResult = await verifyTurnstile(
        input.turnstileToken,
        ip === "unknown" ? null : ip,
      );
      if (!tsResult.ok) {
        throw new TRPCError({
          code: "FORBIDDEN",
          message: "TURNSTILE_FAILED",
        });
      }

      // Per-IP limiter on the gate submit. Tight: 5 / hour.
      await enforceTrpc(
        "authSignUp",
        ip,
        "Too many email submissions. Please wait a few minutes and try again.",
      );

      const email = input.email.trim().toLowerCase();

      // Email-uniqueness gate (one free render per email globally).
      // We check the partial unique index by doing an explicit lookup
      // first so we can return a clean error message, letting the
      // index throw would surface a Prisma constraint error.
      const existing = await prisma.profile.findFirst({
        where: {
          free_render_email: email,
          // Allow the caller's own row through, submitting the same
          // email twice from the same anon session is a no-op refresh,
          // not a violation.
          NOT: { id: ctx.user.id },
        },
        select: { id: true },
      });
      if (existing) {
        throw new TRPCError({
          code: "CONFLICT",
          message: "EMAIL_ALREADY_USED_FREE",
        });
      }

      // Resolve country from the geo cookie/header for downstream
      // analytics + Resend Audience segmentation.
      const country =
        ctx.req?.headers.get("x-vercel-ip-country") ??
        ctx.req?.headers.get("cf-ipcountry") ??
        null;

      // Atomically claim the lock + record the capture.
      const capture = await prisma.$transaction(async (tx) => {
        await tx.profile.update({
          where: { id: ctx.user.id },
          data: { free_render_email: email },
        });
        return tx.emailCaptureEvent.create({
          data: {
            anon_user_id: ctx.user.id,
            email,
            ip,
            country,
            design_id: input.designId ?? null,
            render_id: input.renderId ?? null,
            status: "pending",
          },
          select: { id: true },
        });
      });

      // Best-effort Resend Audiences push. The reconcile cron retries
      // any row where `status='pending'` and `resend_synced_at IS NULL`.
      try {
        const synced = await addToAudience(email, {
          country: country ?? undefined,
          designId: input.designId ?? undefined,
          renderId: input.renderId ?? undefined,
        });
        if (synced) {
          await prisma.emailCaptureEvent
            .update({
              where: { id: capture.id },
              data: {
                status: "sent",
                resend_synced_at: new Date(),
              },
            })
            .catch(() => undefined);
        }
      } catch (err) {
        reportError("auth.requestEmailUpgrade.resend_audience_failed", err, {
          captureId: capture.id,
          userId: ctx.user.id,
        });
      }

      return {
        ok: true,
        captureId: capture.id,
        // The client uses this in the magic-link redirect target.
        renderId: input.renderId ?? null,
      };
    }),

  /**
   * Called by the sign-up forms when `supabase.auth.signUp` rejects an
   * email with `user_already_exists`. That error doesn't only mean "you
   * have an account", it also fires when the email is still parked on
   * an abandoned anonymous session from a previous free-render attempt
   * that never clicked the confirmation link (see `requestEmailUpgrade`
   * above). Without this, that visitor is locked out of signing up with
   * their own email until the `cleanup-anon-users` cron eventually
   * reaps the row (up to 14 days later).
   *
   * Deliberately narrow: only deletes a `profiles` row that (a) is
   * still anonymous, i.e. the `on_auth_user_upgraded` trigger never
   * flipped it, meaning the confirmation link was never clicked - and
   * (b) whose `auth.users` email really is this address and really is
   * unconfirmed. A real, confirmed account is never touched.
   */
  releaseStaleEmail: publicProcedure
    .input(z.object({ email: z.string().email().max(254) }))
    .mutation(async ({ ctx, input }) => {
      const ip = ctx.req ? ipFromRequest(ctx.req) : "unknown";
      await enforceTrpc(
        "authSignUp",
        ip,
        "Too many attempts. Please wait a few minutes and try again.",
      );

      const email = input.email.trim().toLowerCase();

      const stale = await prisma.profile.findFirst({
        where: { free_render_email: email, is_anonymous: true },
        select: { id: true },
      });
      if (!stale) return { released: false };

      const supabase = getSupabaseAdmin();
      const { data, error } = await supabase.auth.admin.getUserById(
        stale.id,
      );
      if (error || !data?.user) return { released: false };
      if (data.user.email?.toLowerCase() !== email) return { released: false };
      if (data.user.email_confirmed_at) return { released: false };

      const { error: delErr } = await supabase.auth.admin.deleteUser(
        stale.id,
      );
      if (delErr && !/not.?found/i.test(delErr.message)) {
        reportError("auth.releaseStaleEmail.delete_failed", delErr, {
          userId: stale.id,
        });
        return { released: false };
      }

      return { released: true };
    }),
});
